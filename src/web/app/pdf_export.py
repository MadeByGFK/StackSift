"""PDF export for StackSift analysis reports (Phase 2B).

Generates a PDF from a stored analysis result's storage_manifest JSON.
Uses fpdf2 (pure Python, no system dependencies).
"""

import json
from datetime import datetime, timezone
from io import BytesIO


def generate_report_pdf(manifest_json: str, filename: str = "report") -> bytes:
    """Generate a PDF report from a stored analysis result.

    Args:
        manifest_json: The Result.storage_manifest JSON (analysis data).
        filename: Original log filename for the report header.

    Returns:
        PDF file bytes.
    """
    from fpdf import FPDF

    try:
        data = json.loads(manifest_json)
    except (json.JSONDecodeError, TypeError):
        data = {}

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()

    # Header
    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 12, "StackSift Analysis Report", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(100, 100, 100)
    pdf.cell(0, 8, f"File: {filename}", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 8, f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
             new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(5)

    # Health summary
    health = data.get("health", {})
    if health:
        pdf.set_font("Helvetica", "B", 14)
        pdf.cell(0, 10, "Summary", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 11)
        label = health.get("label", "Unknown")
        pdf.cell(0, 8, f"Health: {label}", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(3)

    # Stats
    results = data.get("results", {})
    if results:
        pdf.set_font("Helvetica", "B", 14)
        pdf.cell(0, 10, "Statistics", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 11)
        for key in ("total_lines", "parsed_lines", "error_count", "warn_count"):
            if key in results:
                label = key.replace("_", " ").title()
                pdf.cell(0, 7, f"{label}: {results[key]}", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(3)

    # Top findings / signals
    findings = data.get("findings", []) or data.get("signals", []) or []
    if findings:
        pdf.set_font("Helvetica", "B", 14)
        pdf.cell(0, 10, "Key Findings", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 10)
        for i, finding in enumerate(findings[:20], 1):  # Limit to 20
            if isinstance(finding, dict):
                text = finding.get("message", finding.get("description", str(finding)))
            else:
                text = str(finding)
            # Truncate long findings
            if len(text) > 200:
                text = text[:197] + "..."
            pdf.multi_cell(0, 6, f"{i}. {text}")
            pdf.ln(1)

    # Footer
    pdf.ln(5)
    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(100, 100, 100)
    pdf.cell(0, 8, "Generated by StackSift (stacksift.goodfolkdigital.com)",
             new_x="LMARGIN", new_y="NEXT", align="C")

    buf = BytesIO()
    pdf.output(buf)
    return buf.getvalue()
