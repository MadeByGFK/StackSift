def _counting_builds(monkeypatch):
    """Count COMPLETED sample builds: the PDF stage is the last stage
    of the pipeline, so a successful generate_deep_dive_pdf call inside
    the sample build is exactly one fully successful build. (Failed
    attempts at earlier stages never reach it; a failed PDF stage
    raises before the success increment.)"""
    from app import pdf_export as pdf_mod
    real_pdf = pdf_mod.generate_deep_dive_pdf
    state = {"success": 0}

    def counting(*a, **k):
        out = real_pdf(*a, **k)
        state["success"] += 1
        return out

    monkeypatch.setattr(pdf_mod, "generate_deep_dive_pdf", counting)
    return state


