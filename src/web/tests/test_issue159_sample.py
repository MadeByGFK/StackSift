def _row_counts(sessions):
    from app import models
    db = sessions()
    try:
        return {
            "results": db.query(models.Result).count(),
            "operations": db.query(models.Operation).count(),
            "ledger": db.query(models.CreditLedger).count(),
            "accounts": db.query(models.CreditAccount).count(),
            "grants": db.query(models.CreditGrant).count(),
            "users": db.query(models.User).count(),
            "d2_links": db.query(models.D2VisitorLink).count(),
        }
    finally:
        db.close()


