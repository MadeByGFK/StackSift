@pytest.mark.parametrize("stage", ["analyze", "build", "validate", "pdf"])
def test_sample_failure_at_each_stage_500_unpublished_then_recovers(
        sample_client, monkeypatch, stage):
    from app import pdf_export as pdf_mod

    state = _counting_builds(monkeypatch)
    originals = {
        "analyze": main.analyze_upload,
        "build": dd.build_deep_dive,
        "validate": dd.validate_artifact,
        "pdf": pdf_mod.generate_deep_dive_pdf,
    }
    counting_wrapper = main.analyze_upload

    def _raise(*a, **k):
        raise RuntimeError(f"injected {stage} failure")

    if stage == "analyze":
        monkeypatch.setattr(main, "analyze_upload", _raise)
    elif stage == "build":
        monkeypatch.setattr(dd, "build_deep_dive", _raise)
    elif stage == "validate":
        monkeypatch.setattr(dd, "validate_artifact", _raise)
    else:
        monkeypatch.setattr(pdf_mod, "generate_deep_dive_pdf", _raise)

    assert sample_client.get("/sample-report").status_code == 500
    assert sample_client.get("/sample-report/pdf").status_code == 500
    assert main._SAMPLE_CACHE is None, "failure must publish nothing"

    # Remove ONLY the fault: the next request retries the full pipeline.
    if stage == "analyze":
        monkeypatch.setattr(main, "analyze_upload", counting_wrapper)
    elif stage == "build":
        monkeypatch.setattr(dd, "build_deep_dive", originals["build"])
    elif stage == "validate":
        monkeypatch.setattr(dd, "validate_artifact", originals["validate"])
    else:
        monkeypatch.setattr(pdf_mod, "generate_deep_dive_pdf",
                            originals["pdf"])

    r = sample_client.get("/sample-report")
    assert r.status_code == 200, r.text[:300]
    assert LEAD in r.text and BANNER in r.text
    assert sample_client.get("/sample-report/pdf").status_code == 200
    # Exactly one successful build after recovery, shared by both routes.
    assert state["success"] == 1
    assert sample_client.get("/sample-report").status_code == 200
    assert state["success"] == 1


