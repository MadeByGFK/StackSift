def _alarm_free_analyze():
    """The REAL analyze_upload with use_alarm=False.

    TestClient serves requests off the main thread, where arming
    SIGALRM raises — the same constraint that makes the paid fixtures
    precompute their reports. The genuine parsing pipeline still runs;
    only the alarm (a production main-thread deadline) is off.
    """
    from app.service import analyze_upload as real_analyze

    def _run(filename, content, **kwargs):
        kwargs.pop("use_alarm", None)
        return real_analyze(filename, content, use_alarm=False)

    return _run


def _reset():
    # getattr-guarded so the file also runs on the pre-build tree:
    # there the reset simply does not exist yet (teeth classification).
    reset = getattr(main, "_reset_sample_cache", None)
    if reset is not None:
        reset()


