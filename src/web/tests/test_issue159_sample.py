def test_teeth_stale_projection_substitution_is_detectable(sample_client):
    """Substituting a stale hardcoded projection into the cache changes
    what is served — so the provenance assertions above (fresh lead +
    sequence) would fail against it. Passes here by asserting the stale
    content is exactly what differs."""
    artifact = _sample_artifact()
    stale = dd.public_projection(dd.validate_artifact(artifact))
    stale["brief"]["lead"]["template"] = "stale hardcoded lead"
    cache = main._get_sample_cache()
    main._SAMPLE_CACHE = {**cache, "projection": stale}
    try:
        body = sample_client.get("/sample-report").text
    finally:
        _reset()
    # The Brief's lead line is what provenance pins (the lead template
    # also appears in the appendix as a group heading).
    assert "Investigation lead:</strong> stale hardcoded lead" in body
    assert "Investigation lead:</strong> connection pool exhausted" \
        not in body


