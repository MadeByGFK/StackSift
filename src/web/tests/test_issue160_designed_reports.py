def _page_runs(data: bytes):
    """Geometry harness: per page, in order, return
    (runs, rects) where a run is dict(font=BaseFont, x, y, text) and a
    rect is dict(color=(r,g,b) 0-255, x, y, w, h) for filled rects."""
    objs = _streams_by_obj(data)
    # Font object num -> BaseFont name; font object num -> cmap.
    font_info = {}
    for num, (header, _s) in objs.items():
        m = re.search(rb"/BaseFont /[A-Z]+\+([A-Za-z0-9]+)", header)
        if m:
            font_info[num] = m.group(1).decode()
    cmaps = {}
    for num, (header, _s) in objs.items():
        m = re.search(rb"/ToUnicode (\d+) 0 R", header)
        if m:
            target = objs.get(int(m.group(1)))
            if target and target[1]:
                cmaps[num] = _parse_cmap(target[1])
    # Resource name -> font object num (single shared /Resources dict).
    name_to_font = {}
    for _num, (header, _s) in objs.items():
        for name, ref in re.findall(rb"/(F\d+) (\d+) 0 R", header):
            name_to_font[name.decode()] = int(ref)
    # Page order from the Pages object's /Kids.
    kids = []
    mediabox = (595.28, 841.89)
    for _num, (header, _s) in objs.items():
        if b"/Type /Pages" in header:
            km = re.search(rb"/Kids \[(.*?)\]", header, re.DOTALL)
            if km:
                kids = [int(n) for n in
                        re.findall(rb"(\d+) 0 R", km.group(1))]
            mm = re.search(rb"/MediaBox \[0 0 ([0-9.]+) ([0-9.]+)\]",
                           header)
            if mm:
                mediabox = (float(mm.group(1)), float(mm.group(2)))
    pages = []
    for kid in kids:
        header, _s = objs[kid]
        cm = re.search(rb"/Contents (\d+) 0 R", header)
        stream = objs[int(cm.group(1))][1] if cm else b""
        # Replace each literal string with a marker so the operator
        # scan below cannot mistake string bytes for operators.
        literals = []
        skeleton = bytearray()
        i = 0
        while i < len(stream):
            if stream[i:i + 1] == b"(":
                raw, i = _read_literal(stream, i)
                skeleton += b"\x00%d\x00" % len(literals)
                literals.append(raw)
            else:
                skeleton += stream[i:i + 1]
                i += 1
        text = skeleton.decode("latin-1")
        token_re = re.compile(
            r"\x00(\d+)\x00|/(F\d+) [0-9.]+ Tf|"
            r"(-?[0-9.]+) (-?[0-9.]+) Td|"
            r"([0-9.]+) ([0-9.]+) ([0-9.]+) (?:rg|RG)|"
            r"(-?[0-9.]+) (-?[0-9.]+) (-?[0-9.]+) (-?[0-9.]+) re|"
            r" f(?=\s|$)")
        runs, rects = [], []
        font, x, y = None, 0.0, 0.0
        color = (0, 0, 0)
        pending_rect = None
        for m in token_re.finditer(text):
            if m.group(1) is not None:
                raw = literals[int(m.group(1))]
                decoded = _decode_codes(
                    raw, cmaps.get(name_to_font.get(font, 0), {}))
                runs.append({"font": font_info.get(
                    name_to_font.get(font, 0), font or ""),
                    "x": x, "y": y, "text": decoded, "color": color})
            elif m.group(2):
                font = m.group(2)
            elif m.group(3) is not None:
                x, y = float(m.group(3)), float(m.group(4))
            elif m.group(5) is not None:
                color = tuple(round(float(m.group(g)) * 255)
                              for g in (5, 6, 7))
            elif m.group(8) is not None:
                pending_rect = tuple(float(m.group(g))
                                     for g in (8, 9, 10, 11))
            elif pending_rect:
                rx, ry, rw, rh = pending_rect
                rects.append({"color": color, "x": rx, "y": ry,
                              "w": rw, "h": rh})
                pending_rect = None
        pages.append({"runs": runs, "rects": rects,
                      "width": mediabox[0], "height": mediabox[1]})
    return pages


def _all_runs(data: bytes):
    return [run for page in _page_runs(data) for run in page["runs"]]


def _fill_colors(data: bytes):
    objs = _streams_by_obj(data)
    colors = set()
    for _num, (_h, stream) in objs.items():
        if not stream:
            continue
        for m in re.finditer(rb"([0-9.]+) ([0-9.]+) ([0-9.]+) (?:rg|RG)",
                             stream):
            colors.add(tuple(round(float(v) * 255)
                             for v in m.groups()))
    return colors


