# ---------------------------------------------------------------------------
# PDF text extraction (stdlib only). fpdf2 embeds subset TTFs whose
# content streams carry glyph IDs, so text is rebuilt from each font's
# ToUnicode CMap; core-font (fallback) strings decode as cp1252.
# ---------------------------------------------------------------------------


def _streams_by_obj(data: bytes):
    out = {}
    for m in re.finditer(rb"(\d+) 0 obj(.*?)endobj", data, re.DOTALL):
        num = int(m.group(1))
        body = m.group(2)
        sm = re.search(rb"stream\r?\n(.*)\r?\nendstream", body, re.DOTALL)
        if not sm:
            out[num] = (body, None)
            continue
        raw = sm.group(1)
        try:
            dec = zlib.decompress(raw)
        except zlib.error:
            dec = raw
        out[num] = (body[: sm.start()], dec)
    return out


def _parse_cmap(stream: bytes):
    mapping = {}
    text = stream.decode("latin-1", "replace")
    for block in re.findall(r"beginbfchar(.*?)endbfchar", text, re.DOTALL):
        for src, dst in re.findall(r"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>", block):
            mapping[int(src, 16)] = bytes.fromhex(dst).decode(
                "utf-16-be", "replace")
    for block in re.findall(r"beginbfrange(.*?)endbfrange", text, re.DOTALL):
        for lo, hi, dst in re.findall(
                r"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>", block):
            lo_i, hi_i, base = int(lo, 16), int(hi, 16), int(dst, 16)
            for code in range(lo_i, hi_i + 1):
                mapping[code] = chr(base + (code - lo_i))
        for lo, hi, arr in re.findall(
                r"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s*\[(.*?)\]",
                block, re.DOTALL):
            lo_i = int(lo, 16)
            for i, dst in enumerate(re.findall(r"<([0-9A-Fa-f]+)>", arr)):
                mapping[lo_i + i] = bytes.fromhex(dst).decode(
                    "utf-16-be", "replace")
    return mapping


def _read_literal(stream: bytes, i: int):
    assert stream[i:i + 1] == b"("
    out = bytearray()
    depth = 1
    i += 1
    while i < len(stream) and depth:
        b = stream[i]
        if b == 0x5C:  # backslash
            nxt = stream[i + 1:i + 2]
            if nxt in b"nrtbf":
                out.append({b"n": 10, b"r": 13, b"t": 9, b"b": 8,
                            b"f": 12}[nxt])
                i += 2
            elif nxt in b"()\\":
                out.append(nxt[0])
                i += 2
            elif nxt.isdigit():
                j = i + 1
                oct_digits = b""
                while j < len(stream) and len(oct_digits) < 3 \
                        and stream[j:j + 1].isdigit():
                    oct_digits += stream[j:j + 1]
                    j += 1
                out.append(int(oct_digits, 8) & 0xFF)
                i = j
            elif nxt in b"\r\n":
                i += 2
                if nxt == b"\r" and stream[i:i + 1] == b"\n":
                    i += 1
            else:
                out.append(nxt[0] if nxt else 0)
                i += 2
        elif b == 0x28:
            depth += 1
            out.append(b)
            i += 1
        elif b == 0x29:
            depth -= 1
            if depth:
                out.append(b)
            i += 1
        else:
            out.append(b)
            i += 1
    return bytes(out), i


def _decode_codes(raw: bytes, cmap) -> str:
    if cmap:
        return "".join(
            cmap.get((raw[i] << 8) | raw[i + 1], "")
            for i in range(0, len(raw) - 1, 2))
    return raw.decode("cp1252", "replace")


def extract_pdf_text(data: bytes) -> str:
    objs = _streams_by_obj(data)
    font_cmaps = {}
    for num, (header, _stream) in objs.items():
        m = re.search(rb"/ToUnicode (\d+) 0 R", header)
        if m:
            target = objs.get(int(m.group(1)))
            if target and target[1]:
                font_cmaps[num] = _parse_cmap(target[1])
    name_to_font = {}
    for _num, (header, _stream) in objs.items():
        for name, ref in re.findall(rb"/(F\d+) (\d+) 0 R", header):
            name_to_font[name.decode()] = int(ref)
    chunks = []
    for _num, (_header, stream) in objs.items():
        if not stream or b" Tf" not in stream:
            continue
        cmap = {}
        i = 0
        while i < len(stream):
            if stream[i:i + 1] == b"/":
                m = re.match(rb"/(F\d+) [0-9.]+ Tf", stream[i:])
                if m:
                    cmap = font_cmaps.get(
                        name_to_font.get(m.group(1).decode()), {})
                    i += m.end()
                    continue
                i += 1
                continue
            if stream[i:i + 1] == b"(":
                raw, i = _read_literal(stream, i)
                chunks.append(_decode_codes(raw, cmap))
                continue
            if stream[i:i + 1] == b"<" and stream[i:i + 2] != b"<<":
                m = re.match(rb"<([0-9A-Fa-f\s]+)>", stream[i:])
                if m:
                    hexraw = bytes.fromhex(
                        re.sub(rb"\s", b"", m.group(1)).decode())
                    chunks.append(_decode_codes(hexraw, cmap))
                    i += m.end()
                    continue
                i += 1
                continue
            i += 1
    return "\n".join(chunks)


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


